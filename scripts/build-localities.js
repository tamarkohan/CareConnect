/**
 * scripts/build-localities.js
 *
 * Builds src/data/israelLocalities.ts – every Israeli locality (cities, towns,
 * kibbutzim, moshavim, villages) with its English and Hebrew name – for the
 * "Where are you now?" picker. Source: the Central Bureau of Statistics list,
 * as packaged in the npm package "israel-geolocation" (MIT licence).
 *
 *   npm pack israel-geolocation && tar -xzf israel-geolocation-*.tgz
 *   node scripts/build-localities.js package/dist/locations.json
 *
 * Places already in src/data/israelPlaces.ts (with our spelling and
 * neighborhoods) are left out; their official and Hebrew names are kept
 * for searching (CITY_NAMES).
 */
const fs = require("fs");
const path = require("path");

// CBS English names are cut at 20 letters; these are completed from the Hebrew name.
const FIXES = {
  "BET YIZHAQ-SH. HEFER": "Bet Yizhaq-Sha'ar Hefer",
  "GIV'AT HAYYIM(ME'UHA": "Giv'at Hayyim (Me'uhad)",
  "SHOSHANNAT HAAMAQIM(": "Zuqe Yam",
  "ASHDOT YA'AQOV(ME'UH": "Ashdot Ya'aqov (Me'uhad)",
  "EN KAREM-B.S.HAQLA'I": "En Karem (Agricultural School)",
  "KA'ABIYYE-TABBASH-HA": "Ka'abiyye-Tabbash-Hajajre",
  "KEFAR ROZENWALD(ZAR.": "Kefar Rozenwald (Zar'it)",
  "NIZZANA (QEHILAT HIN": "Nizzana (Educational Community)",
  "QIRYAT YE'ARIM(INSTI": "Qiryat Ye'arim (Institution)",
};
// By Hebrew name: no English name in the source, or two places with the same one.
const ENGLISH = {
  "סנסנה": "Sansana", "חברון": "Hebron", "קצר א-סר": "Qasr al-Sir", "כמאנה": "Kamane",
  "ח'ואלד (שבט)": "Khawaled (Tribe)", "צוחר": "Tzohar",
};
// Our spelling in israelPlaces.ts → the CBS English name, where they look too different to match.
const SAME_AS = {
  "Acre (Akko)": "AKKO", "Safed (Tzfat)": "ZEFAT", "Modi'in-Maccabim-Re'ut": "MODI'IN-MAKKABBIM-RE",
  "Ra'anana": "RA'ANANA", "Nahariya": "NAHARIYYA", "Eilat": "ELAT", "Elad": "EL'AD", "Gedera": "GEDERA",
  "Harish": "HARISH", "Karmiel": "KARMI'EL",
};

// Same rules as src/data/placeSearch.ts.
const RULES = [[/tz|ts/g, "z"], [/ch|kh/g, "h"], [/ph/g, "f"], [/th/g, "t"], [/q|c/g, "k"], [/w|v/g, "b"]];
const normWord = (w) => {
  let x = w.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^\p{L}]/gu, "");
  for (const [re, to] of RULES) x = x.replace(re, to);
  return x.replace(/(.)\1+/g, "$1");
};
const norm = (s) => s.split(/[\s\-–()/,]+/).map(normWord).join("");
const skeleton = (s) => { const n = norm(s); return n.charAt(0) + n.slice(1).replace(/[aeiouy]/g, ""); };

// "MA'AGAN MIKHA'EL" → "Ma'agan Mikha'el"
const titleCase = (s) => s.toLowerCase().replace(/(^|[\s\-(])(\p{L})/gu, (_, b, c) => b + c.toUpperCase()).replace(/\s*\(/g, " (");

const [, , input] = process.argv;
const cbs = JSON.parse(fs.readFileSync(input, "utf8"));
const root = path.join(__dirname, "..");
const placesSrc = fs.readFileSync(path.join(root, "src/data/israelPlaces.ts"), "utf8");
const curated = [...placesSrc.matchAll(/city: "((?:[^"\\]|\\.)*)"/g)].map((m) => m[1].replace(/\\'/g, "'"));

const used = new Set();
const curatedHe = {};
for (const city of curated) {
  const want = SAME_AS[city];
  const hit = want
    ? cbs.find((c) => c.nameEn === want)
    : cbs.find((c) => c.nameEn && skeleton(c.nameEn) === skeleton(city.replace(/\s*\(.*\)$/, "")));
  if (!hit) throw new Error(`No CBS match for ${city}`);
  used.add(hit.id);
  curatedHe[city] = [titleCase(hit.nameEn), hit.name];
}

const others = cbs
  .filter((c) => !used.has(c.id))
  .map((c) => [ENGLISH[c.name] || FIXES[c.nameEn] || (c.nameEn && titleCase(c.nameEn.trim())), c.name.trim()])
  .filter(([en]) => en)
  .sort((a, b) => a[0].localeCompare(b[0]));
const names = [...curated, ...others.map(([en]) => en)];
const dupes = names.filter((n, i) => names.indexOf(n) !== i);
if (dupes.length) throw new Error(`Same English name twice (add them to ENGLISH): ${dupes.join(", ")}`);

const q = (s) => JSON.stringify(s);
const out = `// ── israelLocalities.ts ──────────────────────────────────────────────
// GENERATED by scripts/build-localities.js – don't edit by hand.
// Every Israeli locality (cities, towns, kibbutzim, moshavim, villages) not
// already in israelPlaces.ts, as [English, Hebrew]. Source: Central Bureau of
// Statistics list via the npm package "israel-geolocation" (MIT licence).

/** The cities in israelPlaces.ts: [official English spelling, Hebrew], for searching. */
export const CITY_NAMES: Record<string, [string, string]> = {
${Object.entries(curatedHe).map(([en, [cbsEn, he]]) => `    ${q(en)}: [${q(cbsEn)}, ${q(he)}],`).join("\n")}
};

export const LOCALITIES: [string, string][] = [
${others.map(([en, he]) => `    [${q(en)}, ${q(he)}],`).join("\n")}
];
`;
fs.writeFileSync(path.join(root, "src/data/israelLocalities.ts"), out);
console.log(`${curated.length} cities matched, ${others.length} more localities written.`);
